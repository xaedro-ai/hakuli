"""Render benchmark tables from results JSON files.

Usage:
    python benchmarks/table.py
"""

from __future__ import annotations

import json
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
RESULTS = BENCH_DIR / "results"

DISPLAY_NAMES = {
    "hakuli": "Hakuli",
    "adamw": "AdamW",
    "galore": "GaLore",
    "qgalore": "Q-GaLore",
    "apollo": "APOLLO (official)",
}


def load_published() -> list[dict]:
    path = RESULTS / "published.json"
    if not path.exists():
        return []
    return json.loads(path.read_text(encoding="utf-8"))["anchors"]


def load_runs() -> list[dict]:
    runs = []
    for path in sorted(RESULTS.glob("*.json")):
        if path.name == "published.json":
            continue
        runs.append(json.loads(path.read_text(encoding="utf-8")))
    return runs


def fmt(value, unit=""):
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:g}{unit}"
    return f"{value}{unit}"


def main() -> None:
    lines = [
        "# Benchmark results",
        "",
        "Generated by `benchmarks/table.py`. Published anchors are measured by the",
        "respective authors on the hardware listed; our runs use one shared protocol",
        "(see `benchmarks/README.md`).",
        "",
        "| Method | Model | GPU | Batch | Peak VRAM | Tokens/s | Final loss | Source |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for anchor in load_published():
        vram = anchor.get("peak_vram_reported")
        vram_text = "does not fit" if vram is None else f"{vram:g} GiB (as reported)"
        lines.append(
            "| {method} | {model} | {gpu} | {batch} | {vram} | — | — | published: {source} |".format(
                method=anchor["method"],
                model=anchor["model"],
                gpu=anchor["gpu"],
                batch=anchor.get("batch", "—"),
                vram=vram_text,
                source=anchor["source"],
            )
        )
    for run in load_runs():
        lines.append(
            "| {method} | {model} | {gpu} | {batch} | {vram} GiB | {tps} | {loss} | this work |".format(
                method=DISPLAY_NAMES.get(run["method"], run["method"]),
                model=run["model"],
                gpu=run["gpu"],
                batch=run["batch_size"],
                vram=fmt(run["peak_vram_gib"]),
                tps=fmt(run["tokens_per_sec"]),
                loss=fmt(run["final_loss"]),
            )
        )
    output = BENCH_DIR / "RESULTS.md"
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
